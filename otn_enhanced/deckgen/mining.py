"""Empirical facts mined from tournament decklists.

Everything in this module is measured, not reasoned about. It answers three
questions the model kept getting wrong by theorising:

* **What is always played?** Cards appearing in most decks of a format are
  slam-dunks regardless of what the economy model computes — Pot of Duality,
  Book of Moon, Dark Hole, Heavy Storm, Effect Veiler. Their value is in the
  format, not in their text.
* **How many copies?** Deck builders run 3 Flamvell Firedog and 1 Flamvell
  Magician. That is a fact about the cards, not something a marginal-gain
  calculation reliably rediscovers.
* **What travels together?** Cards that co-occur far more than chance form real
  packages. Mined by lift, so "both are staples" does not register as synergy.

Output is a cached artifact regenerated by ``deckgen mine``; the scoring code
consumes it read-only.
"""

from __future__ import annotations

import json
import math
from collections import Counter, defaultdict
from dataclasses import dataclass, field

from otn_enhanced.deckgen import cache
from otn_enhanced.deckgen.model import Card

SCHEMA = "deckgen.mined.v1"

#: Formats whose card pool is closest to Over the Nexus (a 2011 game).
#: Tengu *is* the 2011 format; Edison/Crow/Trishula bracket it.
ERA_FORMATS = ("Tengu", "Edison", "Crow", "Trishula")

#: Coverage floor for mining.  Lower than the validation corpus uses: Tengu
#: decks sit around 0.80 because post-cutoff staples (Tour Guide from the
#: Underworld) are not in this ROM, and excluding the format entirely would throw
#: away the single most relevant body of evidence.
MIN_COVERAGE = 0.75


@dataclass
class Mined:
    """Empirical facts about how cards are actually played."""

    decks: int
    formats: dict[str, int] = field(default_factory=dict)
    #: cid -> fraction of decks containing it
    play_rate: dict[int, float] = field(default_factory=dict)
    #: cid -> modal number of copies, given the card is played at all
    playset: dict[int, int] = field(default_factory=dict)
    #: cid -> mean copies when played
    mean_copies: dict[int, float] = field(default_factory=dict)
    #: (cid_a, cid_b) -> lift, for pairs that co-occur well above chance
    pairs: list[tuple[int, int, float, int]] = field(default_factory=list)
    #: tag -> mean play rate of cards carrying it.  This is the *transferable*
    #: half of the evidence: "cards that search get played" is a principle, while
    #: "cid 0x1F3A gets played" is a fact about one card's stat line.  If the ROM's
    #: card properties are randomised, the per-cid rates become wrong for monsters
    #: but these stay true, so power.py falls back to them.
    tag_play_rate: dict[str, float] = field(default_factory=dict)

    def is_staple(self, cid: int, threshold: float) -> bool:
        return self.play_rate.get(cid, 0.0) >= threshold

    def to_json(self) -> dict:
        return {
            "decks": self.decks,
            "formats": self.formats,
            "play_rate": {str(k): round(v, 5) for k, v in self.play_rate.items()},
            "playset": {str(k): v for k, v in self.playset.items()},
            "mean_copies": {str(k): round(v, 3) for k, v in self.mean_copies.items()},
            "pairs": [[a, b, round(l, 3), n] for a, b, l, n in self.pairs],
            "tag_play_rate": {k: round(v, 5) for k, v in self.tag_play_rate.items()},
        }

    @classmethod
    def from_json(cls, d: dict) -> "Mined":
        return cls(
            decks=d["decks"],
            formats=d.get("formats", {}),
            play_rate={int(k): v for k, v in d["play_rate"].items()},
            playset={int(k): v for k, v in d["playset"].items()},
            mean_copies={int(k): v for k, v in d.get("mean_copies", {}).items()},
            pairs=[(a, b, l, n) for a, b, l, n in d.get("pairs", [])],
            tag_play_rate=d.get("tag_play_rate", {}),
        )


def mine(
    decks,
    *,
    min_support: int = 6,
    min_lift: float = 2.5,
    max_pairs: int = 400,
) -> Mined:
    """Measure play rate, playset size and co-occurrence lift.

    *Lift* rather than raw co-occurrence: two staples appear together in most
    decks without being related at all, and counting that as synergy is how a
    "package" miner degenerates into rediscovering the staple list.
    """
    n = len(decks)
    presence: Counter = Counter()
    copies: defaultdict[int, list[int]] = defaultdict(list)
    pair_count: Counter = Counter()

    for d in decks:
        # Main AND Extra: counting only the main deck made every Synchro score a
        # 0% play rate, which silently zeroed the evidence channel for the whole
        # Extra Deck and made it impossible to tell a Level 8 boss from a Level 3
        # nobody plays.
        counts: Counter = Counter(list(d.main) + list(d.extra))
        for cid, k in counts.items():
            presence[cid] += 1
            copies[cid].append(k)
        cids = sorted(counts)
        for i, a in enumerate(cids):
            for b in cids[i + 1:]:
                pair_count[(a, b)] += 1

    play_rate = {cid: c / n for cid, c in presence.items()}
    playset = {cid: Counter(v).most_common(1)[0][0] for cid, v in copies.items()}
    mean_copies = {cid: sum(v) / len(v) for cid, v in copies.items()}

    pairs: list[tuple[int, int, float, int]] = []
    for (a, b), c in pair_count.items():
        if c < min_support:
            continue
        expected = play_rate[a] * play_rate[b] * n
        if expected <= 0:
            continue
        lift = c / expected
        if lift >= min_lift:
            pairs.append((a, b, lift, c))
    # Rank by how much evidence there is, not just by lift: a lift of 40 off six
    # decks is noise next to a lift of 4 off ninety.
    pairs.sort(key=lambda t: -(math.log(t[3]) * t[2]))

    return Mined(
        decks=n,
        formats=dict(Counter(d.format for d in decks)),
        play_rate=play_rate,
        playset=playset,
        mean_copies=mean_copies,
        pairs=pairs[:max_pairs],
    )


def learn_tag_rates(m: "Mined", parsed) -> dict[str, float]:
    """Mean play rate of the cards carrying each behavioural tag.

    The generalisable form of the staple evidence.  Averaged over every card in
    the pool that has the tag — including the ones nobody plays — so a tag only
    scores well if cards carrying it are *typically* played, not merely if one
    famous card has it.
    """
    from collections import defaultdict

    totals: defaultdict[str, list[float]] = defaultdict(list)
    for cid, pc in parsed.items():
        rate = m.play_rate.get(cid, 0.0)
        for tag in pc.tags:
            totals[tag].append(rate)
    return {t: sum(v) / len(v) for t, v in totals.items() if len(v) >= 5}


def era_decks(cards: list[Card], formats: tuple[str, ...] = ERA_FORMATS):
    """Tournament decks from the era-relevant formats, loosely filtered."""
    import json as _json

    from otn_enhanced.deckgen.validate import tournament

    raw = _json.loads(tournament.DECKS_CACHE.read_text(encoding="utf-8"))
    raw = [d for d in raw if d.get("format") in formats]
    old = tournament.MIN_COVERAGE
    try:
        tournament.MIN_COVERAGE = MIN_COVERAGE
        return tournament.map_to_pool(raw, cards)
    finally:
        tournament.MIN_COVERAGE = old


def load(cards: list[Card], *, force: bool = False) -> Mined:
    """Cached mined facts."""
    from otn_enhanced.deckgen.validate import tournament

    def build():
        from otn_enhanced.deckgen.text.parse import parse_pool

        m = mine(era_decks(cards))
        parsed, _ = parse_pool(cards)
        m.tag_play_rate = learn_tag_rates(m, parsed)
        return m.to_json()

    raw = cache.cached(
        SCHEMA,
        [tournament.DECKS_CACHE, cache.CACHE_DIR / "deckgen.cards.v1.json"],
        build,
        force=force,
    )
    return Mined.from_json(raw)


def report(m: Mined, cards: list[Card], top: int = 25) -> str:
    by = {c.cid: c for c in cards}
    lines = [
        f"mined {m.decks} decks from {m.formats}",
        "",
        f"top {top} staples (play rate, modal copies):",
    ]
    for cid, r in sorted(m.play_rate.items(), key=lambda kv: -kv[1])[:top]:
        if cid not in by:
            continue
        lines.append(
            f"  {r*100:5.1f}%  x{m.playset.get(cid, 1)}  "
            f"(mean {m.mean_copies.get(cid, 0):.1f})  {by[cid].name[:40]}"
        )
    lines += ["", f"top {top} co-occurring pairs (lift, decks):"]
    for a, b, lift, c in m.pairs[:top]:
        if a not in by or b not in by:
            continue
        lines.append(f"  lift {lift:5.1f}  n={c:3}  {by[a].name[:30]:32} + {by[b].name[:30]}")
    return "\n".join(lines)
