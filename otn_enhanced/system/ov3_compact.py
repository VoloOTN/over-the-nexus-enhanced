"""Step 0: ov3 compaction -- free dead / duplicated overlay-3 code for injected stubs.

Applies otn_enhanced/effects/pool_blocks.py (generated by gen_pool.py from a
scan of stock + chain; see notes/ov3-compaction-findings.md):

  * REDIRECTS  -- repoint every reference to a duplicate function copy at its identical twin;
  * NULL_SLOTS -- null phantom cls-record slot words that point into a freed run (only where
                  live records of that table+slot are already null, so the engine tolerates it);
  * FREE_RUNS  -- zero-fill the freed runs (phantom-only code + the duplicate copies).

MUST be the first ov3 step after CardWorkshop's speed/View Mode (system.cardworkshop_speed_view):
every edit is asserted against stock bytes, and every later patch
asserts its own originals, so an overlap with a card patch fails the build loudly.

Nothing here changes live behaviour: the freed bytes are reachable only from records of cids
with no card_prop row (never dispatched), and the redirected copies are byte-identical.
The freed space is NOT claimed by anything yet -- that is Phase C (ov3 allocator).
"""
from __future__ import annotations

import struct
import zlib

from otn_enhanced.asm.effect_shim import _bl
from otn_enhanced.effects.pool_blocks import FREE_RUNS, NULL_SLOTS, REDIRECTS
from otn_enhanced.rom.overlay_io import RAM_BASE, load_overlay3, save_overlay3
from otn_enhanced.effects.common import u32 as _u32

SRC = "data/over_the_nexus/working/rom.nds"
OUT = "data/over_the_nexus/working/rom_ov3_compact.nds"




def apply(ov: bytearray) -> None:
    for s, e, crc in FREE_RUNS:  # all preconditions before any write
        assert zlib.crc32(ov[s - RAM_BASE:e - RAM_BASE]) == crc, f"run 0x{s:08X} is not stock"
    for site, kind, old, new in REDIRECTS:
        o = site - RAM_BASE
        if kind == "bl":
            assert bytes(ov[o:o + 4]) == _bl(site, old), f"0x{site:08X} is not bl 0x{old:08X}"
            ov[o:o + 4] = _bl(site, new)
        else:
            assert _u32(ov, site) == old, f"0x{site:08X} is not .word 0x{old:08X}"
            struct.pack_into("<I", ov, o, new)
    for site, old in NULL_SLOTS:
        assert _u32(ov, site) == old, f"phantom slot 0x{site:08X} is not 0x{old:08X}"
        struct.pack_into("<I", ov, site - RAM_BASE, 0)
    for s, e, _ in FREE_RUNS:
        ov[s - RAM_BASE:e - RAM_BASE] = bytes(e - s)


def main(src: str = SRC, out: str = OUT) -> None:
    rom, data = load_overlay3(src)
    ov = bytearray(data)
    apply(ov)
    save_overlay3(rom, bytes(ov), out)
    print(f"ov3 compact: freed {sum(e - s for s, e, _ in FREE_RUNS)} B in {len(FREE_RUNS)} runs, "
          f"{len(REDIRECTS)} redirects, {len(NULL_SLOTS)} phantom slots nulled -> {out}")


def verify(out: str = OUT) -> None:
    """Final-ROM guard: redirects in place, and NO live cls record points into a freed run
    (a later patch re-keying a phantom record in place would otherwise jump into freed code)."""
    from otn_enhanced.tools.donor_scan import cards

    _, data = load_overlay3(out)
    words = set(struct.unpack_from(f"<{len(data) // 4}I", data))
    for site, kind, old, new in REDIRECTS:
        if kind == "bl":  # ov3 code never moves
            assert bytes(data[site - RAM_BASE:site - RAM_BASE + 4]) == _bl(site, new), f"redirect 0x{site:08X} lost"
        else:  # cls rows shift with count-neutral inserts: the stale pointer must be gone everywhere
            assert old not in words, f"stale pointer 0x{old:08X} to a freed duplicate is still in ov3"
    from otn_enhanced.knowledge.check_allocations import parse_cave3_slots
    claimed = [(s["addr"], s["addr"] + s["size"]) for s in parse_cave3_slots()]  # Phase C stubs: legal
    live = set(cards())
    tables = [(_u32(data, 0x0224A398), _u32(data, 0x0224A39C)), (_u32(data, 0x0224A3A0), _u32(data, 0x0224A3A4)),
              (_u32(data, 0x0224A3A8), _u32(data, 0x0224A3AC)), (0x02279D74, 0x308)]
    for base, n in tables:
        for i in range(n):
            a = base + i * 24
            if _u32(data, a) not in live:
                continue
            for k in range(1, 6):
                p = _u32(data, a + 4 * k) & ~1
                if any(s <= p < e for s, e in claimed):
                    continue
                assert not any(s <= p < e for s, e, _ in FREE_RUNS), (
                    f"live cid 0x{_u32(data, a):04X} slot{k} points into freed ov3 run 0x{p:08X}")
    print(f"ov3 compact verify OK: {len(REDIRECTS)} redirects, no live record into {len(FREE_RUNS)} freed runs")


if __name__ == "__main__":
    main()
    verify()
