def _convert_deck_format_to_ydc_codec(deck_entry: dict) -> dict:
    """Convert deck data format from doTheThing to ydc_codec format."""
    # Convert header from list of uint16 to base64-encoded 8 bytes
    header_uint16s = deck_entry.get("header", [])
    header_bytes = b""
    for val in header_uint16s:
        header_bytes += val.to_bytes(2, "little")
    header_b64 = base64.b64encode(header_bytes).decode("ascii")
    
    return {
        "format": "ydc.v1",
        "header_b64": header_b64,
        "main_size": deck_entry.get("main_deck_size", 0),
        "extra_size": deck_entry.get("extra_deck_size", 0),
        "side_size": 0,  # No side deck in OTN format
        "main_deck": deck_entry.get("main_deck_names", []),
        "extra_deck": deck_entry.get("extra_deck_names", []),
        "side_deck": [],
        "trailing_b64": base64.b64encode(b"").decode("ascii"),  # Empty trailing for now
    }

def main(src: str, out: str) -> None:
    # Step 8: Copy modified ROM to output
    import shutil
    print(f"Copying {src} to {out}...")
    shutil.copy(src, out+".bak")
    # Step 1: Extract deck.pac from ROM
    args = {
        "rom_path": out+".bak",
        "file_path_in_rom": "Data_arc_pac/deck.pac",
        "output_file": "data/over_the_nexus/working/deck.pac"
    }
    import argparse
    args = argparse.Namespace(**args)
    print(f"Extracting deck.pac from {out}...")
    extract_file(args)
    
    # Step 2: Parse deck.pac and get deck data as JSON
    print("Parsing deck.pac and generating deck.json...")
    deck_data = doTheThing("data/over_the_nexus/working/deck.pac")
    with open("data/over_the_nexus/working/deck.json", "w") as f:
        json.dump(deck_data, f, indent=4)
    
    # Step 3: Apply changes to deck_data
    print("Applying changes to deck_data...")
    for f, ydc in CHANGES.items():
        fn = ydc.file_name
        print(f"Applying changes to {f}[{fn}]...")
        if not isinstance(ydc, YDC):
            raise ValueError(f"CHANGES entry for {fn} is not a YDC instance")
        if fn not in deck_data:
            raise ValueError(f"Deck file {fn} not found in deck.pac")
        deck_entry = deck_data[fn]
        deck_entry['main_deck_names'] = ydc.main
        deck_entry['extra_deck_names'] = ydc.extra
        deck_entry['main_deck_size'] = len(ydc.main)
        deck_entry['extra_deck_size'] = len(ydc.extra)
    
    # Step 4: Encode modified YDC files and build replacements map
    print("Encoding modified YDC files and preparing replacements...")
    with open("data/over_the_nexus/working/deck.pac", "rb") as f:
        deck_pac_data = f.read()
    
    archive = parse_pac(deck_pac_data, "data/over_the_nexus/working/deck.pac")
    replacements_by_index = {}
    # CHANGES is keyed by friendly names; the PAC files are named by their .ydc
    # filename, so match on the YDC.file_name values, not the CHANGES keys.
    #
    # deck_data (above) is keyed by doTheThing()'s decode of the RAW embedded name, control
    # bytes and all -- "Brave RD"'s name has a genuine leading \x1b in the ROM. archive.files'
    # get_clean_name() strips non-printables for matching. Bridge clean -> raw here so that
    # stray byte doesn't silently drop the deck from replacements_by_index (it used to: neither
    # side matched, so the `if` below was never entered and the deck stayed stock).
    raw_by_clean = {"".join(c for c in ydc.file_name if c.isprintable()): ydc.file_name
                    for ydc in CHANGES.values()}
    print("Building replacements for modified YDC files...")
    for idx, pac_file in enumerate(archive.files):
        clean_name = pac_file.get_clean_name()
        raw_name = raw_by_clean.get(clean_name)
        if raw_name is not None:
            # Convert from doTheThing format to ydc_codec format
            converted_deck = _convert_deck_format_to_ydc_codec(deck_data[raw_name])
            ydc_json_str = json.dumps(converted_deck)
            ydc_binary = encode_ydc_from_json(ydc_json_str)
            replacements_by_index[idx] = ydc_binary

    if not replacements_by_index:
        raise ValueError(
            "No decks in CHANGES matched deck.pac contents -- nothing to patch. "
            f"Expected one of {sorted(raw_by_clean)} in the archive."
        )

    # Step 5: Apply PAC changes using the canonical PAC writer
    print("Applying PAC changes...")
    modified_deck_pac = build_modified_pac(
        deck_pac_data,
        "data/over_the_nexus/working/deck.pac",
        replacements_by_index
    )
    
    # Step 6: Write modified deck.pac
    print("Writing modified deck.pac...")
    with open("data/over_the_nexus/working/deck_modified.pac", "wb") as f:
        f.write(modified_deck_pac)
    
    # Step 7: Replace file in ROM
    print("Replacing modified deck.pac in ROM...")
    replace_args = argparse.Namespace(
        rom_path=out+".bak",
        file_path_in_rom="Data_arc_pac/deck.pac",
        input_file="data/over_the_nexus/working/deck_modified.pac"
    )
    replace_file(replace_args)
    os.remove(out)
    shutil.copy(out+'.bak', out)
    os.remove(out+'.bak')
    print("Modified deck.pac has been replaced in ROM.")

if __name__ == "__main__":
    main(src=SRC, out=OUT)