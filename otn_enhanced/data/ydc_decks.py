class YDC:
    file_name = None
    main = []
    extra = []
    def __init__(self, fn, main, extra, no_check=False):
        self.file_name = fn
        self.main = main
        self.extra = extra
        if not no_check:
            try:
                self.validate()
            except ValueError as e:
                raise ValueError(f"{fn}: {e}") from None
    
    def validate(self):
        # An entry may be a card NAME (str) or a Konami ID (int, or a dict
        # carrying one).  Names are how the hand-written CHANGES below are
        # written and stay supported; ids exist because the name table cannot
        # express every card.
        #
        # A duplicated name (alt arts, tokens) resolves to its FIRST record only,
        # so a specific printing needs its id.  ydc_codec._entry_to_konami_id
        # already accepts ids; this only taught validate() to agree.
        def _bad(entry):
            if isinstance(entry, int):
                return None if 0 <= entry <= 0xFFFF else f"{entry!r} out of range"
            if isinstance(entry, dict):
                kid = entry.get("konami_id")
                if isinstance(kid, int) and 0 <= kid <= 0xFFFF:
                    return None
                return f"{entry!r} has no usable konami_id"
            if isinstance(entry, str):
                return None if card_name_to_konami_id(entry) is not None else f"{entry!r}"
            return f"{entry!r} is not a name, id or {{konami_id: ...}}"

        if not self.file_name:
            raise ValueError("YDC file name is required")
        if not isinstance(self.main, list) or not isinstance(self.extra, list):
            raise ValueError("Main and Extra decks must be lists")
        # Check main deck is >= 40 and <= 60 cards
        if len(self.main) < 40 or len(self.main) > 40:
            raise ValueError(f"Main deck must have between 40 and 60 cards, got {len(self.main)}")
        # Check extra deck is <= 15 cards
        if len(self.extra) > 15:
            raise ValueError(f"Extra deck must have 15 or fewer cards, got {len(self.extra)}")
        if len(self.extra) < 15:
            print(f"[{self.file_name}] Extra deck has fewer than 15 cards, got {len(self.extra)}")
        # Check every card resolves to a konami ID
        unresolved = [b for b in (_bad(e) for e in self.main + self.extra) if b]
        if unresolved:
            raise ValueError(f"Cards that do not resolve to a konami ID: {unresolved}")

