def accepted(cid: int, own: int) -> set[int]:
    """Genre values a module that writes its own *own* value should accept in verify()."""
    return {own} | ({GENRE[cid][1]} if cid in GENRE else set())


def _find_pac(rom):
    fid = rom.filenames.idOf(PAC)
    orig = bytes(rom.files[fid])
    return fid, orig, parse_pac(orig, PAC)


def _tables(pac, archive):
    f = {x.get_clean_name().lower(): x for x in archive.files}
    cp, gn, ix, nm = f["card_prop.bin"], f["card_genre.bin"], f["card_indx_e.bin"], f["card_name_e.bin"]
    n = (cp.size - 8) // 8
    assert n == (gn.size - 8) // 8, "card_prop / card_genre not parallel"
    rows = {}
    for i in range(n):
        cid = int.from_bytes(pac[cp.address + 8 + i * 8:][:2], "little") & 0x3FFF
        if cid in GENRE:
            off = struct.unpack_from("<I", pac, ix.address + (i + 1) * 8)[0]  # card_indx: no header
            end = pac.index(b"\0", nm.address + off)
            name = bytes(pac[nm.address + off:end]).decode("latin-1")
            rows[cid] = (gn.address + 8 + i * 8, name)
    return rows


def main(src: str = SRC, out: str = OUT) -> None:
    if src != out:
        shutil.copyfile(src, out)
    rom = ndspy.rom.NintendoDSRom.fromFile(out)
    fid, orig, archive = _find_pac(rom)
    pac = bytearray(orig)
    done = 0
    for cid, (go, name) in _tables(pac, archive).items():
        want_name, want = GENRE[cid]
        if name != want_name:
            continue                      # card not patched in (yet) -- leave the donor alone
        pac[go:go + 8] = want.to_bytes(8, "little")
        done += 1
    rom.files[fid] = bytes(pac)
    rom.saveToFile(out)
    print(f"card_genre: {done}/{len(GENRE)} re-donored cards present and tagged")


def verify(out: str = OUT) -> bool:
    rom = ndspy.rom.NintendoDSRom.fromFile(out)
    _, pac, archive = _find_pac(rom)
    ok = True
